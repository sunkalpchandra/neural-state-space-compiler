#!/usr/bin/env python3
"""Experiment L — build the "compiled vs manual vs large sequence model" suite.

Reads one or more compile reports, extracts the selected candidate spec and writes
configs/experiments/benchmarks/compiled_vs_manual.yaml so the compiler's choice is trained
under exactly the same benchmark protocol (epochs, seeds, windows) as the hand-picked
latent models and the baselines of `synthetic_core`. Runs with identical configs are
reused from the registry by the suite runner.

    python experiments/synthetic/make_compiled_suite.py results/compile/lorenz63 results/compile/vanderpol
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from nssc.compiler.report import CompileReport
from nssc.search.space import CandidateSpec
from nssc.utils.config import load_yaml

BASE = Path("configs/experiments/benchmarks/synthetic_core.yaml")
OUT = Path("configs/experiments/benchmarks/compiled_vs_manual.yaml")


def main(dirs: list[str]) -> None:
    base = load_yaml(BASE)
    suite = {"name": "compiled_vs_manual", "datasets": {}, "seeds": base["seeds"], "windows": base["windows"],
             "training": base["training"], "eval": base["eval"], "models": {}, "baselines": {},
             "per_dataset": {}, "output_dir": "results/raw/benchmarks/compiled_vs_manual"}
    for d in dirs:
        rep = CompileReport.load(Path(d) / "compile_report.json")
        spec = CandidateSpec.from_dict(rep.selected)
        ds_name = rep.dataset.get("system") or rep.dataset.get("source") or Path(d).name
        ds_key = Path(d).name
        suite["datasets"][ds_key] = base["datasets"].get(ds_key, {"_file": f"configs/datasets/{ds_key}.yaml"})
        model_cfg = spec.model_config()
        suite["per_dataset"][ds_key] = {"models": {f"compiled_{spec.name.replace('+', '_').replace('@', '_')}": model_cfg}}
        # runner-up and the manual reference for the same dataset
        if len(rep.ranking) > 1:
            ru = rep.ranking[1]
            cid = ru["candidate_id"]
            ru_spec = None
            for c in yaml.safe_load(open(Path(d) / "candidates.json")):
                if CandidateSpec.from_dict(c).id == cid:
                    ru_spec = CandidateSpec.from_dict(c)
            if ru_spec is not None:
                suite["per_dataset"][ds_key]["models"][
                    f"runnerup_{ru_spec.name.replace('+', '_').replace('@', '_')}"] = ru_spec.model_config()
        print(f"{ds_key}: selected {spec.name} ({ds_name})")
    # the manual latent models + baselines are shared with synthetic_core (identical hashes → reused)
    suite["models"] = base["models"]
    suite["baselines"] = base["baselines"]
    for k, v in (base.get("per_dataset") or {}).items():
        if k in suite["per_dataset"]:
            suite["per_dataset"][k]["models"] = {**v.get("models", {}), **suite["per_dataset"][k]["models"]}
    OUT.write_text("# Generated by experiments/synthetic/make_compiled_suite.py — Experiment L.\n"
                   + yaml.safe_dump(suite, sort_keys=False))
    print("wrote", OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
